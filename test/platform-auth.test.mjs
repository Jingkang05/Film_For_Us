test("tokens use authenticated encryption; tampering and wrong keys fail",()=>{
  const key=randomBytes(32), value={access_token:"private",refresh_token:"private-refresh"};
  const sealed=sealTokens(value,key); assert.ok(!sealed.includes("private")); assert.deepEqual(openTokens(sealed,key),value);
  assert.throws(()=>openTokens(sealed,randomBytes(32)));
  const bytes=Buffer.from(sealed,"base64url");bytes[30]^=1;assert.throws(()=>openTokens(bytes.toString("base64url"),key));
});
test("project environment isolation rejects production credentials in development and preview",()=>{
  const ref="a".repeat(20),dev="b".repeat(20);
  const env={SUPABASE_URL:`https://${dev}.supabase.co`,SUPABASE_PUBLISHABLE_KEY:"sb_publishable_synthetic",DATABASE_URL:`postgresql://postgres.${dev}:synthetic@aws-0-ap-south-1.pooler.supabase.com:6543/postgres`,SESSION_ENCRYPTION_KEY:"a".repeat(64),SUPABASE_ENVIRONMENT:"preview",VERCEL_ENV:"preview",SUPABASE_PRODUCTION_REF:ref};
  assert.equal(platformConfig(env).ref,dev);
  assert.throws(()=>platformConfig({...env,SUPABASE_URL:`https://${ref}.supabase.co`}),/Non-production/);
  assert.throws(()=>platformConfig({...env,SUPABASE_ENVIRONMENT:"production"}),/must match/);
  assert.throws(()=>platformConfig({...env,DATABASE_URL:`postgresql://postgres.${ref}:secret@aws-0-ap-south-1.pooler.supabase.com:6543/postgres`}),/belong/);
  assert.throws(()=>platformConfig({...env,SUPABASE_PUBLISHABLE_KEY:"sb_secret_forbidden"}),/publishable/);
  assert.throws(()=>platformConfig({...env,DATABASE_URL:"synthetic-private-password-invalid-url"}),error=>error.message==="Invalid DATABASE_URL." && !error.input);
});
test("OTP registration/login, invalid/expired/replayed codes, encrypted persistent sessions, revocation, CSRF and migration",async t=>{
  const db=await postgresFixture();t.after(()=>db.close());
  const provider=authFixture(db),config={encryptionKey:randomBytes(32)},origin="https://film.example";
  let auth=createPlatformAuth({db,config,origin,clientFactory:provider.clientFactory});
  const req={method:"POST",headers:{origin},socket:{remoteAddress:"127.0.0.1"}};
  let cookie;
  const res={setHeader(name,value){if(name==="Set-Cookie")cookie=value;}};
  const handle=(path,value,request=req)=>auth.handle(request,res,path,async()=>value);
  const email="administrator@example.test";
  await assert.rejects(handle("/api/auth/otp",{email},{...req,headers:{origin:"https://attacker.invalid"}}),{status:403});
  await handle("/api/auth/otp",{email});
  await assert.rejects(handle("/api/auth/otp",{email}),{status:429});
  await assert.rejects(handle("/api/auth/verify",{email,code:"999999"}),{status:401});
  provider.pending.get(email).expires=0;
  await assert.rejects(handle("/api/auth/verify",{email,code:"123456"}),{status:401});
  provider.pending.get(email).expires=Date.now()+600000;
  await handle("/api/auth/verify",{email,code:"123456"});
  assert.match(cookie,/^__Host-ffu_session=[a-f0-9]{64}; Path=\/; HttpOnly; SameSite=Lax; Max-Age=1209600; Secure$/);
  assert.ok(!cookie.includes("access_token"));
  await assert.rejects(handle("/api/auth/verify",{email,code:"123456"}),{status:401});
  const authenticated={...req,headers:{...req.headers,cookie:cookie.split(";")[0]}};
  const user=await auth.requireUser(authenticated);
  assert.equal(user.email,email);
  auth=createPlatformAuth({db,config,origin,clientFactory:provider.clientFactory});
  assert.equal((await auth.requireUser(authenticated)).userId,user.userId,"survives backend instance restart");
  const {rows:[session]}=await db.pg.query("select * from ffu.app_sessions");
  const tokenData=openTokens(session.encrypted_tokens,config.encryptionKey);tokenData.expires_at=0;
  await db.pg.query("update ffu.app_sessions set encrypted_tokens=$1",[sealTokens(tokenData,config.encryptionKey)]);
  await Promise.all([auth.requireUser(authenticated),auth.requireUser(authenticated)]);
  assert.equal(provider.refreshes,1,"concurrent refresh serialized");
  const state=stateFixture(),digest=contentHash(state);
  await assert.rejects(importState({db,state,digest,ownerId:user.userId,administratorEmail:"unverified@example.test"}),/must agree/);
  assert.throws(()=>verifyLegacyAdministrator(state,"not-the-administrator-password"),/failed/);
  const imported=await importState({db,state,digest,ownerId:user.userId,administratorEmail:email});assert.equal(imported.albums,1);
  assert.equal((await importState({db,state,digest,ownerId:user.userId,administratorEmail:email})).alreadyImported,true);
  const changed=structuredClone(state);changed.album.revision++;
  await assert.rejects(importState({db,state:changed,digest:contentHash(changed),ownerId:user.userId,administratorEmail:email}),/already exists/);
  const stored=await db.pg.query("select draft,owner_id from ffu.albums");assert.equal(contentHash(stored.rows[0].draft),contentHash(JSON.parse(state.album.draft)));
  assert.equal(stored.rows[0].owner_id,user.userId);
  await handle("/api/auth/logout",{},authenticated);
  assert.match(cookie,/Max-Age=0/);
  await assert.rejects(auth.requireUser(authenticated),{status:401});
  assert.ok(provider.revoked.has(user.sessionId));
  await db.pg.query("delete from ffu.rate_limits");
  await handle("/api/auth/otp",{email});await handle("/api/auth/verify",{email,code:"123456"});
  const newReq={...req,headers:{...req.headers,cookie:cookie.split(";")[0]}};
  const nextUser=await auth.requireUser(newReq);assert.equal(nextUser.userId,user.userId,"existing-user login");
  await db.pg.query("delete from auth.sessions where id=$1",[nextUser.sessionId]);
  await assert.rejects(auth.requireUser(newReq),{status:401},"upstream revocation checked on every protected request");
});
