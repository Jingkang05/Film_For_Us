import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { openAlbum, initialAlbum } from "../server/album.mjs";

test("an existing Phase 2 SQLite album upgrades additively with IDs, images, owner and sessions intact", async t => {
  const directory = await mkdtemp(join(tmpdir(), "film-legacy-")), path = join(directory, "album.sqlite");
  t.after(() => rm(directory, { recursive: true, force: true }));
  const db = new DatabaseSync(path);
  db.exec(`CREATE TABLE album (id INTEGER PRIMARY KEY, share_id TEXT, revision INTEGER, draft TEXT, published_revision INTEGER, published TEXT);
    CREATE TABLE media (id TEXT PRIMARY KEY, source BLOB, thumb BLOB, full BLOB);
    CREATE TABLE session (token_hash TEXT PRIMARY KEY, expires_at INTEGER);
    CREATE TABLE local_owner (id INTEGER PRIMARY KEY, salt TEXT, password_hash TEXT);`);
  const row = initialAlbum(); row.share_id = "OhqQkmPtTAlxEkHH";
  const content = JSON.parse(row.draft), photo = randomUUID();
  content.title = "Synthetic legacy album"; content.letter = "No personal content";
  content.rolls[0].photos = [{ id: photo, note: "A note", date: "2026-11-11" }];
  row.draft = JSON.stringify(content); row.published = row.draft; row.published_revision = row.revision;
  db.prepare("INSERT INTO album VALUES (1, ?, ?, ?, ?, ?)").run(row.share_id, row.revision, row.draft, row.published_revision, row.published);
  db.prepare("INSERT INTO media VALUES (?, ?, ?, ?)").run(photo, Buffer.from("original"), Buffer.from("thumb"), Buffer.from("full"));
  db.prepare("INSERT INTO session VALUES (?, ?)").run("existing-session", Date.now() + 100000);
  db.prepare("INSERT INTO local_owner VALUES (1, ?, ?)").run("a".repeat(32), "b".repeat(128));
  const rawRow = db.prepare("SELECT * FROM album").get(); db.close();
  let store = openAlbum(path);
  const original = await store.published(row.share_id);
  assert.equal(original.rolls[0].photos[0].id, photo);
  assert.equal(original.rolls[0].photos[0].full, `/api/a/${row.share_id}/media/${photo}/full`);
  assert.equal(Buffer.from(await store.media(photo, "full", row.share_id)).toString(), "full");
  assert.equal(await store.sessionValid("existing-session"), true);
  assert.equal((await store.localOwner()).password_hash, "b".repeat(128));
  const other = await store.create("Another memory"); store.close();
  store = openAlbum(path);
  assert.equal((await store.list()).length, 2);
  assert.equal((await store.manage(other.shareId)).album.title, "Another memory");
  assert.deepEqual(await store.published(row.share_id), original); store.close();
  const unchanged = new DatabaseSync(path, { readOnly: true });
  assert.deepEqual(unchanged.prepare("SELECT * FROM album").get(), rawRow);
  assert.equal(Buffer.from(unchanged.prepare("SELECT source FROM media WHERE id = ?").get(photo).source).toString(), "original");
  unchanged.close();
});
